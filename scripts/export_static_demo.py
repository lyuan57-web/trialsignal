"""Export a recruiter-friendly static snapshot from the local TrialSignal warehouse.

The public demo intentionally ships a bounded subset of public ClinicalTrials.gov
records. The full ingestion pipeline, relational warehouse, and model training remain
in the repository; this exporter turns their outputs into a browser-only artifact.
"""

from __future__ import annotations

import argparse
import json
import sqlite3
from datetime import UTC, datetime
from pathlib import Path

import joblib

from trialsignal.data_quality import quality_summary
from trialsignal.risk_model import row_to_features
from trialsignal.survival import duration_benchmark


ACTIVE_STATUSES = {
    "RECRUITING",
    "NOT_YET_RECRUITING",
    "ACTIVE_NOT_RECRUITING",
    "ENROLLING_BY_INVITATION",
}


def load_rows(database: Path) -> list[dict]:
    with sqlite3.connect(database) as connection:
        connection.row_factory = sqlite3.Row
        rows = connection.execute(
            """
            SELECT s.*, sp.canonical_name sponsor,
                   COUNT(DISTINCT sc.condition_id) condition_count,
                   GROUP_CONCAT(DISTINCT c.normalized_name) conditions
            FROM studies s
            JOIN sponsors sp USING(sponsor_id)
            LEFT JOIN study_conditions sc USING(nct_id)
            LEFT JOIN conditions c USING(condition_id)
            GROUP BY s.nct_id
            ORDER BY s.start_date DESC, s.nct_id
            """
        ).fetchall()
    return [dict(row) for row in rows]


def select_demo_rows(rows: list[dict]) -> list[dict]:
    """Build overlapping recruiter-relevant cohorts without cherry-picking outcomes."""

    def condition_match(row: dict, phrase: str) -> bool:
        haystack = f"{row.get('conditions') or ''} {row.get('title') or ''}".lower()
        return phrase in haystack

    cohorts = (
        [row for row in rows if condition_match(row, "lung cancer")][:250],
        [row for row in rows if condition_match(row, "melanoma")][:200],
        [row for row in rows if condition_match(row, "breast cancer")][:200],
        [row for row in rows if "PHASE3" in json.loads(row.get("phases_json") or "[]")][:200],
        [row for row in rows if row.get("overall_status") in ACTIVE_STATUSES][:200],
        rows[:200],
    )
    selected: dict[str, dict] = {}
    for cohort in cohorts:
        for row in cohort:
            selected.setdefault(row["nct_id"], row)
    return list(selected.values())


def public_trial(row: dict) -> dict:
    conditions = sorted(set(filter(None, (row.get("conditions") or "").split(","))))
    return {
        "nct_id": row["nct_id"],
        "title": row["title"],
        "sponsor": row["sponsor"],
        "sponsor_class": row.get("sponsor_class"),
        "study_type": row.get("study_type"),
        "overall_status": row.get("overall_status"),
        "phases": row.get("phases_json") or "[]",
        "countries": row.get("countries_json") or "[]",
        "enrollment_count": row.get("enrollment_count"),
        "start_date": row.get("start_date"),
        "completion_date": row.get("completion_date"),
        "conditions": conditions,
        "intervention_types": json.loads(row.get("intervention_types_json") or "[]"),
        "primary_purpose": row.get("primary_purpose"),
        "intervention_model": row.get("intervention_model"),
        "allocation": row.get("allocation"),
        "masking": row.get("masking"),
    }


def build_payload(database: Path, model_path: Path) -> dict:
    all_rows = load_rows(database)
    demo_rows = select_demo_rows(all_rows)
    artifact = joblib.load(model_path)
    probabilities = artifact["model"].predict_proba(
        [row_to_features(row) for row in demo_rows]
    )[:, 1]
    return {
        "metadata": {
            "generated_at": datetime.now(UTC).isoformat(),
            "source": "ClinicalTrials.gov API v2",
            "source_record_count": len(all_rows),
            "demo_record_count": len(demo_rows),
            "scope_note": "Bounded public demo snapshot generated by the full local pipeline.",
        },
        "trials": [public_trial(row) for row in demo_rows],
        "risk_probabilities": {
            row["nct_id"]: round(float(probability), 8)
            for row, probability in zip(demo_rows, probabilities, strict=True)
        },
        "risk_model": {
            "model_metrics": artifact["metrics"],
            "feature_policy": artifact["feature_policy"],
            "interpretation": (
                "Historical benchmark probability, not a causal estimate or clinical recommendation."
            ),
        },
        "quality": quality_summary(database),
        "duration": duration_benchmark(database, phase="PHASE3"),
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database", type=Path, default=Path("data/trialsignal.db"))
    parser.add_argument("--model", type=Path, default=Path("models/adverse_outcome.joblib"))
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    payload = build_payload(args.database, args.model)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    encoded = json.dumps(payload, ensure_ascii=False, separators=(",", ":"))
    args.output.write_text(
        f"window.TRIALSIGNAL_DEMO_DATA={encoded};\n", encoding="utf-8"
    )
    print(
        json.dumps(
            {
                "output": str(args.output),
                "source_records": payload["metadata"]["source_record_count"],
                "demo_records": payload["metadata"]["demo_record_count"],
                "bytes": args.output.stat().st_size,
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
